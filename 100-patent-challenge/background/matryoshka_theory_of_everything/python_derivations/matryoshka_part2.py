    H_j = sp.Symbol('H_j')  # Hilbert space for shell j
    
    # Define the total Hilbert space as the tensor product
    H_total = sp.Symbol('H_{total}')
    
    print("The quantum state space of the Matryoshka framework is built from")
    print("tensor products of individual shell Hilbert spaces:")
    
    # Define tensor product notation
    tensor_prod = r'\otimes'
    
    # Define the equation for the total Hilbert space
    H_total_eq = sp.Eq(H_total, 
                     sp.Symbol(r'H_1 \otimes H_2 \otimes \cdots \otimes H_\omega \otimes \cdots'))
    
    # Display the equation
    sp.pprint(H_total_eq)
    
    # Define state vectors for quantum states on shells
    psi_i = sp.Symbol(r'\psi_i')
    psi_j = sp.Symbol(r'\psi_j')
    
    # Display shell state vector properties
    print("\nState vectors for individual shells:")
    sp.pprint(sp.Symbol(r'|\psi_i\rangle \in H_i'))
    
    # Tensor product of states
    psi_total = sp.Symbol(r'\psi_{total}')
    psi_total_eq = sp.Eq(sp.Symbol(r'|\psi_{total}\rangle'),
                        sp.Symbol(r'|\psi_1\rangle \otimes |\psi_2\rangle \otimes \cdots'))
    
    print("\nTotal state vector:")
    sp.pprint(psi_total_eq)
    
