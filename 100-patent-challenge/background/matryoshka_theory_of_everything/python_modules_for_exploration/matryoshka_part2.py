    print("\n4. Integration for each independent internal momentum:")
    sp.pprint(rule4)
    
    # Rule 5: Symmetry factors
    print("\n5. Symmetry factors as in standard field theory")
    
    # Example diagram: 1-loop self-energy
    print("\nExample: 1-loop self-energy correction in shell framework")
    
