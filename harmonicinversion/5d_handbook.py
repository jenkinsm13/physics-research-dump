def hadamard_transform(x):
  """Calculates the Hadamard transform of a vector."""
  N = len(x)
  y = np.zeros(N)
  for i in range(N):
    for j in range(N):
      y[i] += x[j] * np.exp(-2j * np.pi * i * j / N)
